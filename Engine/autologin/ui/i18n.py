def region_display(lang_code, key):
    return REGION_NAMES.get(lang_code, REGION_NAMES["en"]).get(key, key)


def region_display_list(lang_code):
    rn = REGION_NAMES.get(lang_code, REGION_NAMES["en"])
    order = REGION_ORDER.get(lang_code, REGIONS)
    return [rn.get(r, r) for r in order]


def region_key_from_display(lang_code, display):
    rn = REGION_NAMES.get(lang_code, REGION_NAMES["en"])
    for key, name in rn.items():
        if name == display:
            return key
    return display
